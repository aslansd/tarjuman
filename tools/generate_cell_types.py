"""Regenerate tarjuman/_cell_types.py from the canonical NeuroML2 definitions.

Usage:
    python tools/generate_cell_types.py path/to/NeuroML2CoreTypes/Cells.xml

NeuroML's abstract cells are LEMS ComponentTypes like any other, and tarjuman
already has an interpreter for those. Rather than reimplement
``izhikevich2007Cell`` in Python and hope the transcription is right, the
canonical ``<Dynamics>`` is embedded verbatim and fed to the same interpreter
that handles a model's own custom component types. The point cells and the
cells a model defines itself then travel one code path.

The ancestors of each requested type are pulled in automatically, so the
emitted document resolves on its own.
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

#: The cell ComponentTypes to extract. Ancestors are added automatically.
WANTED = [
    # The integrate-and-fire family. tarjuman builds these with a dedicated
    # channel, but a model may extend one (c302 parameter set B does), and the
    # inherited parameters have to come from somewhere.
    "iafCell",
    "iafRefCell",
    "iafTauCell",
    "iafTauRefCell",
    # Cells the LEMS interpreter drives directly.
    "izhikevich2007Cell",
    "adExIaFCell",
    "hindmarshRose1984Cell",
    # Dimensionless and multi-compartment abstract cells. Included so that a
    # model using one is rejected for the right reason rather than as an
    # unknown type.
    "izhikevichCell",
    "fitzHughNagumoCell",
    "fitzHughNagumo1969Cell",
    "pinskyRinzelCA3Cell",
]

HEADER = '''"""Canonical LEMS definitions of the NeuroML 2 abstract cell types.

AUTO-GENERATED by ``tools/generate_cell_types.py`` from the ``Cells.xml``
shipped with the NeuroML2 repository. Do not edit by hand.

These are the ComponentTypes verbatim, dynamics and all, so that the point
cells are driven by the same LEMS interpreter as a model's own custom types
instead of being reimplemented in Python. ``tarjuman.lems.builtins`` parses
this string once and merges the result into the component registry.
"""

from __future__ import annotations

#: Extracted from NeuroML2 {source}
CELL_TYPES_XML = """\\
{body}"""
'''


def main(path: str) -> None:
    root = ET.parse(path).getroot()
    namespace = root.tag.split("}")[0] + "}" if root.tag.startswith("{") else ""

    by_name = {
        element.get("name"): element
        for element in root.iter(f"{namespace}ComponentType")
        if element.get("name")
    }

    # Close the requested set over `extends`, keeping bases before children so
    # the emitted document can be read top to bottom.
    ordered: list[str] = []

    def add(name: str) -> None:
        if name in ordered or name not in by_name:
            return
        parent = by_name[name].get("extends")
        if parent:
            add(parent)
        ordered.append(name)

    for name in WANTED:
        if name not in by_name:
            raise SystemExit(f"{path} has no ComponentType '{name}'")
        add(name)

    chunks = []
    for name in ordered:
        element = by_name[name]
        # Strip the namespace so the emitted document needs no declarations.
        for node in element.iter():
            if node.tag.startswith("{"):
                node.tag = node.tag.split("}", 1)[1]
        ET.indent(element, space="    ")
        text = ET.tostring(element, encoding="unicode").rstrip()
        chunks.append("\n".join("    " + line for line in text.splitlines()))

    body = '<Lems>\n\n' + "\n\n".join(chunks) + "\n\n</Lems>\n"
    body = body.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')

    output = Path(__file__).parent.parent / "tarjuman" / "_cell_types.py"
    output.write_text(
        HEADER.format(source=Path(path).name, body=body), encoding="utf-8"
    )
    print(f"wrote {output} with {len(ordered)} component types:")
    print("  " + ", ".join(ordered))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
